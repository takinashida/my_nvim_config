-- Вес точки брайля по её месту в клетке (x: 0..1, y: 0..3).
local WEIGHTS = {
  [0] = { [0] = 0x01, [1] = 0x02, [2] = 0x04, [3] = 0x40 },
  [1] = { [0] = 0x08, [1] = 0x10, [2] = 0x20, [3] = 0x80 },
}

--- Превращает строки брайля в битовую сетку (1 точка = 1 пиксель).
local function decode(lines)
  local cols = 0
  for _, line in ipairs(lines) do
    cols = math.max(cols, #vim.fn.str2list(line))
  end
  local w, h = cols * 2, #lines * 4

  local dots = {}
  for y = 0, h - 1 do
    dots[y] = {}
    for x = 0, w - 1 do
      dots[y][x] = 0
    end
  end

  for row, line in ipairs(lines) do
    for col, codepoint in ipairs(vim.fn.str2list(line)) do
      local bits = codepoint - 0x2800
      if bits >= 0 and bits <= 0xFF then
        for dx = 0, 1 do
          for dy = 0, 3 do
            local weight = WEIGHTS[dx][dy]
            if math.floor(bits / weight) % 2 == 1 then dots[(row - 1) * 4 + dy][(col - 1) * 2 + dx] = 1 end
          end
        end
      end
    end
  end

  return dots, w, h
end

--- Уменьшает сетку: каждая новая точка — среднее по своему блоку.
local function resample(dots, w, h, scale)
  local ow, oh = math.floor(w * scale + 0.5), math.floor(h * scale + 0.5)
  local res = {}

  for y = 0, oh - 1 do
    res[y] = {}
    for x = 0, ow - 1 do
      local x0, x1 = x / scale, (x + 1) / scale
      local y0, y1 = y / scale, (y + 1) / scale
      local total, filled = 0, 0
      for sy = math.floor(y0), math.ceil(y1) - 1 do
        for sx = math.floor(x0), math.ceil(x1) - 1 do
          if sx >= 0 and sx < w and sy >= 0 and sy < h then
            total = total + 1
            filled = filled + dots[sy][sx]
          end
        end
      end
      res[y][x] = (total > 0 and filled / total >= THRESHOLD) and 1 or 0
    end
  end

  return res, ow, oh
end

--- Кодирует битовую сетку обратно в строки брайля.
local function encode(dots, w, h)
  local lines = {}
  for cy = 0, math.ceil(h / 4) - 1 do
    local chars = {}
    for cx = 0, math.ceil(w / 2) - 1 do
      local bits = 0
      for dx = 0, 1 do
        for dy = 0, 3 do
          local x, y = cx * 2 + dx, cy * 4 + dy
          if x < w and y < h and dots[y][x] == 1 then bits = bits + WEIGHTS[dx][dy] end
        end
      end
      chars[#chars + 1] = vim.fn.nr2char(0x2800 + bits)
    end
    lines[#lines + 1] = table.concat(chars)
  end
  return lines
end

--- Арт в нужном масштабе.
local function header()
  local dots, w, h = decode(ART)
  local small, sw, sh = resample(dots, w, h, SCALE)
  return table.concat(encode(small, sw, sh), "\n")
end

